import test from 'node:test';
import assert from 'node:assert/strict';
import mammoth from 'mammoth';
import { Document, Packer, Paragraph } from 'docx';
import { parseQuestionsFromText } from './docxParser.ts';

test('parseQuestionsFromText extracts SOAL blocks, options, answer key, explanation, and weight', () => {
  const sample = `
SOAL 1
Apa fungsi utama mitokondria?
A. Sintesis protein
B. Menghasilkan energi
C. Mengatur keluar masuk zat
D. Menyimpan informasi genetik
Kunci Jawaban: B
Pembahasan: Mitokondria merupakan tempat utama respirasi seluler.
Bobot Nilai: 30

SOAL 2
Organel yang berfungsi dalam sintesis protein adalah...
A. Ribosom
B. Lisosom
C. Vakuola
D. Kloroplas
Kunci Jawaban: A
`;

  const result = parseQuestionsFromText(sample);
  assert.equal(result.questions.length, 2);
  assert.equal(result.questions[0].prompt, 'Apa fungsi utama mitokondria?');
  assert.deepEqual(result.questions[0].options, [
    'Sintesis protein',
    'Menghasilkan energi',
    'Mengatur keluar masuk zat',
    'Menyimpan informasi genetik',
  ]);
  assert.equal(result.questions[0].correctLetter, 'B');
  assert.equal(result.questions[0].correctIndex, 1);
  assert.equal(result.questions[0].points, 30);
  assert.match(result.questions[0].explanation, /respirasi seluler/);
  assert.equal(result.questions[0].missingAnswerKey, false);

  assert.equal(result.questions[1].correctLetter, 'A');
  assert.equal(result.questions[1].correctIndex, 0);
  assert.equal(result.questions[1].points, 20);
});

test('parseQuestionsFromText flags missing answer key with warning', () => {
  const sample = `
1. Berapakah percepatan gravitasi standar di permukaan Bumi?
A) 5,4 m/s2
B) 9,8 m/s2
C) 12,2 m/s2
D) 15,0 m/s2
`;
  const result = parseQuestionsFromText(sample);
  assert.equal(result.questions.length, 1);
  assert.equal(result.questions[0].missingAnswerKey, true);
  assert.equal(result.questions[0].correctIndex, -1);
  assert.ok(result.warnings.length > 0);
});

test('mammoth extracts real DOCX buffer generated by docx library', async () => {
  const doc = new Document({
    sections: [
      {
        children: [
          new Paragraph({ text: 'SOAL 1' }),
          new Paragraph({ text: 'Hukum kekekalan energi menyatakan bahwa energi tidak dapat...' }),
          new Paragraph({ text: 'A. Diciptakan atau dimusnahkan' }),
          new Paragraph({ text: 'B. Berubah bentuk menjadi massa' }),
          new Paragraph({ text: 'C. Berpindah antar benda' }),
          new Paragraph({ text: 'D. Disimpan di dalam pegas' }),
          new Paragraph({ text: 'Kunci Jawaban: A' }),
        ],
      },
    ],
  });

  const buffer = await Packer.toBuffer(doc);
  const extracted = await mammoth.extractRawText({ buffer });
  const parsed = parseQuestionsFromText(extracted.value);
  assert.equal(parsed.questions.length, 1);
  assert.equal(parsed.questions[0].correctLetter, 'A');
  assert.equal(parsed.questions[0].missingAnswerKey, false);
});
